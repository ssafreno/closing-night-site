// Shape (docs/ENGINE_API.md, Papers): papers[id] = { title, body ('\n' breaks, *emphasis*) | html, style, kicker?,
//   signature?, journalTitle?, journal?: false, journalTab?: 'Prompt Book', pages?: [{ title?, body|html, requires?,
//   missing? }] }. Styles (DESIGN §10): playbill, ledger, typed, telegram, notepaper, card, legal, ticket, certificate
//   (engine extras: letter, diary, page, chalk, programme, clipping). Each paper is tagged with its room (the journal
//   groups by it). 'runningorder' is generated by the engine.
import { papers as door } from './papers/door.js';
import { papers as stage } from './papers/stage.js';
import { papers as wardrobe } from './papers/wardrobe.js';
import { papers as pit } from './papers/pit.js';
import { papers as foyer } from './papers/foyer.js';
import { papers as dressing } from './papers/dressing.js';
import { papers as finale } from './papers/finale.js';

export const MODULES = { door, stage, wardrobe, pit, foyer, dressing, finale };

export const papers = {};
for (const [room, mod] of Object.entries(MODULES)) {
  for (const [id, def] of Object.entries(mod || {})) {
    if (id in papers) console.warn(`[papers] ${room} redefines "${id}"`);
    papers[id] = { room, ...def };
  }
}
